/**
 * Build-time injector for the canonical book price.
 *
 * Reads src/content/site-settings.json and writes api/_runtimeConfig.js
 * exporting `bookPriceInr`. The serverless create-order endpoint imports
 * that constant to verify that each submitted order amount matches
 * `bookPriceInr * copies * 100` — i.e. the price can't be tampered with
 * client-side, because the server recomputes it from this build-time value.
 *
 * Why build-time and not runtime? The serverless function cannot read the
 * repo file at runtime (it's deployed as a single bundled function), so we
 * bake the value in at build time. This mirrors how Vite `define` works,
 * but for the /api folder which Vite doesn't process.
 *
 * Output is gitignored — regenerated on every build. Run manually once
 * after clone (`node scripts/build-runtime-config.mjs`) so local dev can
 * resolve the import.
 *
 * Wired into package.json "build" BEFORE tsc/vite.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const SETTINGS_JSON = join(ROOT, 'src', 'content', 'site-settings.json');
const OUT_JS = join(ROOT, 'api', '_runtimeConfig.js');

async function main() {
  const raw = await readFile(SETTINGS_JSON, 'utf8');
  const data = JSON.parse(raw);
  const priceInr = data?.book?.priceInr;

  if (typeof priceInr !== 'number'
    || !Number.isFinite(priceInr)
    || !Number.isInteger(priceInr)
    || priceInr < 1) {
    throw new Error(
      `[build-runtime-config] invalid book.priceInr in ${SETTINGS_JSON} `
      + `(expected a positive integer, got ${JSON.stringify(priceInr)})`,
    );
  }

  const body =
    `// AUTO-GENERATED by scripts/build-runtime-config.mjs — do not edit by hand.\n`
    + `// Regenerated on every build from src/content/site-settings.json.\n`
    + `// Used by api/create-order.js to verify submitted order amounts.\n`
    + `export const bookPriceInr = ${JSON.stringify(priceInr)};\n`;

  await writeFile(OUT_JS, body, 'utf8');
  console.log(`[build-runtime-config] wrote bookPriceInr=${priceInr} to api/_runtimeConfig.js`);
}

main().catch((err) => {
  console.error('[build-runtime-config] failed:', err);
  process.exit(1);
});
